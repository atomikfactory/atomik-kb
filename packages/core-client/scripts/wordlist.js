// Generates `src/wordlist-english.ts` from the BIP-39 English word list that kb-crypto
// vendors for the recovery kit (`crates/kb-crypto/wordlists/english.txt`, MIT, ADR-0017):
//
//   pnpm --filter @atomik-kb/core-client wordlist
//
// The output is committed. The list is checked first (SHA-256 of the official file, 2048
// sorted lowercase words, unique 4-letter prefixes), so a damaged or different list never
// becomes TypeScript. `src/wordlist-english.test.ts` fails when the two files drift apart.

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import process from "node:process";
import { URL, fileURLToPath } from "node:url";

/** SHA-256 of the official BIP-39 English list (ADR-0017, `2f5eed53…dbda`). */
const EXPECTED_SHA256 = "2f5eed53a4727b4bf8880d8f3f199efc90e58503646d9ff8eff3a2ed3b24dbda";
const SOURCE = new URL("../../../crates/kb-crypto/wordlists/english.txt", import.meta.url);
const TARGET = new URL("../src/wordlist-english.ts", import.meta.url);
const WORD_COUNT = 2048;
const WORDS_PER_LINE = 8;

/** Reports a problem with the source list and stops without writing anything. */
function fail(message) {
  process.stderr.write(`wordlist: ${message}\n`);
  process.exit(1);
}

const bytes = readFileSync(SOURCE);
const digest = createHash("sha256").update(bytes).digest("hex");
if (digest !== EXPECTED_SHA256) {
  fail(`${fileURLToPath(SOURCE)} has SHA-256 ${digest}, expected ${EXPECTED_SHA256}`);
}

const words = bytes.toString("utf8").split("\n");
if (words.at(-1) === "") {
  words.pop();
}
if (words.length !== WORD_COUNT) {
  fail(`expected ${String(WORD_COUNT)} words, found ${String(words.length)}`);
}
const prefixes = new Set();
words.forEach((word, index) => {
  if (!/^[a-z]{3,8}$/.test(word)) {
    fail(`line ${String(index + 1)} is not a word of 3 to 8 letters a-z`);
  }
  if (index > 0 && words[index - 1] >= word) {
    fail(`line ${String(index + 1)} is out of order or repeated`);
  }
  const prefix = word.slice(0, 4);
  if (prefixes.has(prefix)) {
    fail(`line ${String(index + 1)} repeats the 4-letter prefix "${prefix}"`);
  }
  prefixes.add(prefix);
});

const lines = [];
for (let start = 0; start < words.length; start += WORDS_PER_LINE) {
  const chunk = words.slice(start, start + WORDS_PER_LINE).map((word) => `"${word}"`);
  lines.push(`  ${chunk.join(", ")},`);
}

const output = `// Generated by \`pnpm --filter @atomik-kb/core-client wordlist\` (scripts/wordlist.js) from
// crates/kb-crypto/wordlists/english.txt: the BIP-39 English word list (MIT), SHA-256
// ${EXPECTED_SHA256}. Never edit by hand.

/**
 * The 2048 BIP-39 English words in order: the word list of the recovery kit (ADR-0017).
 * Every word is 3 to 8 lowercase letters and its first four letters identify it.
 */
export const BIP39_ENGLISH: readonly string[] = Object.freeze([
${lines.join("\n")}
]);
`;

writeFileSync(TARGET, output);
process.stdout.write(`wrote ${fileURLToPath(TARGET)} (${String(words.length)} words)\n`);
