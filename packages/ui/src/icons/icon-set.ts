/** Every icon of the set, in display order. */
export const ICON_LIST: readonly SetIcon[] = ICON_CATEGORIES.flatMap((category) => ICON_SET[category]);

const BY_NAME: ReadonlyMap<string, SetIcon> = new Map(ICON_LIST.map((entry) => [entry.name, entry]));

/** The icon the set stores under `name`; `undefined` for a name it does not know (a newer set's). */
export function iconByName(name: string): SetIcon | undefined {
  return BY_NAME.get(name);
}

/** The name as words, for an accessible name and for the search: `book-open` is "book open". */
export function iconLabel(name: string): string {
  return name.replaceAll("-", " ");
}

/**
 * The icons whose name or keywords hold every word of `query` (a word matches the start of a
 * word of the name or of a keyword), best matches first: a word of the name before a keyword, the
 * order of the set otherwise. An empty query finds nothing: the picker lists the categories then.
 */
export function searchIcons(query: string): readonly SetIcon[] {
  const words = query.toLowerCase().split(/[\s-]+/).filter((word) => word !== "");
  if (words.length === 0) {
    return [];
  }
  const found: { entry: SetIcon; rank: number }[] = [];
  for (const entry of ICON_LIST) {
    const nameWords = entry.name.split("-");
    let rank = 0;
    let all = true;
    for (const word of words) {
      if (nameWords.some((part) => part.startsWith(word))) {
        rank += nameWords[0]?.startsWith(word) === true ? 0 : 1;
      } else if (entry.keywords.some((keyword) => keyword.startsWith(word))) {
        rank += 2;
      } else {
        all = false;
        break;
      }
    }
    if (all) {
      found.push({ entry, rank });
    }
  }
  // Array.prototype.sort is stable: equal ranks keep the order of the set.
  return found.sort((a, b) => a.rank - b.rank).map(({ entry }) => entry);
}
