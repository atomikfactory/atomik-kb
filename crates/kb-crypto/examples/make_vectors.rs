//! Generates the golden vector files of suite 1 under `fixtures/crypto/`:
//!
//! - `derive-key-v1.json`: [`kb_crypto::derive_key`] (HKDF-SHA256 with our label
//!   framing);
//! - `wrap-v1.json`, `passphrase-v1.json`, `sign-v1.json`, `sealed-box-v1.json`,
//!   `envelope-v1.json`, `padding-v1.json`, `stream-v1.json`, `kit-v1.json`: one
//!   golden per persisted or transmitted format of Milestone 4.
//!
//! Run it only when the suite or a format changes on purpose (a new suite id,
//! ADR-0013), and review the diff of the files like a protocol change:
//!
//! ```text
//! cargo run -p kb-crypto --example make_vectors
//! ```
//!
//! Every input is fixed below and every random byte comes from
//! `kb_types::testing::SeededRng` with the seed recorded in the file, so the output
//! is reproducible; the tests regenerate the bytes and compare. The known-answer
//! files from the specifications (`kat-*.json`) are not written here: they are
//! copies of published vectors, not output of our code.
//!
//! The JSON is written by hand rather than through `serde_json` so key order and
//! layout never depend on which serde_json features other crates enable. The tests
//! `derive_key_matches_the_frozen_vector_file` (`src/lib.rs`) and
//! `tests/goldens.rs` read the files back.

// A developer tool, not library code: printing and unwrapping are fine here.
#![allow(clippy::print_stdout, clippy::unwrap_used, clippy::expect_used)]

use std::path::PathBuf;

use kb_crypto::envelope::EnvelopeKind;
use kb_crypto::kit;
use kb_crypto::{
    AgreementSecret, Argon2Params, HKDF_SALT, LABEL_PREFIX, Label, Secret32, SigningKey,
    StreamSealer, derive_key, pad_to_bucket, seal_envelope, seal_to, sign, wrap_key,
    wrap_with_passphrase,
};
use kb_types::testing::SeededRng;

struct Input {
    name: &'static str,
    ikm: [u8; 32],
    label: Label,
    info: Vec<u8>,
}

fn hex(bytes: &[u8]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

/// 32 bytes `f(0), f(1), .., f(31)`.
fn key_from(f: impl Fn(u8) -> u8) -> [u8; 32] {
    let mut key = [0u8; 32];
    for (i, byte) in (0u8..).zip(key.iter_mut()) {
        *byte = f(i);
    }
    key
}

fn inputs() -> Vec<Input> {
    vec![
        // The real use: the local database key from an ARK and a 16-byte install id.
        Input {
            name: "local-db: ARK 00..1f, install id 00 11 .. ff",
            ikm: key_from(|i| i),
            label: Label::LOCAL_DB,
            info: (0u8..16).map(|i| i * 0x11).collect(),
        },
        // Empty info.
        Input {
            name: "space-kek: all-ones key, empty info",
            ikm: [0xff; 32],
            label: Label::SPACE_KEK,
            info: Vec::new(),
        },
        // Pins the 0x00 separator: `keyring` + `-auth` must not equal `keyring-auth`.
        Input {
            name: "keyring: info `-auth` (label/info boundary)",
            ikm: key_from(|i| 0xa0u8.wrapping_add(i)),
            label: Label::KEYRING,
            info: b"-auth".to_vec(),
        },
        // Info longer than an HMAC-SHA256 block (64 bytes).
        Input {
            name: "recovery-id: 100-byte info spanning HMAC blocks",
            ikm: key_from(|i| i.wrapping_mul(7).wrapping_add(3)),
            label: Label::RECOVERY_ID,
            info: (0u8..100).collect(),
        },
    ]
}

fn fixtures_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../fixtures/crypto")
}

fn write(name: &str, contents: &str) {
    let path = fixtures_dir().join(name);
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    std::fs::write(&path, contents).unwrap();
    println!("wrote {}", path.display());
}

fn derive_key_file() -> String {
    let vectors: Vec<String> = inputs()
        .iter()
        .map(|v| {
            let okm = derive_key(&Secret32::from_bytes(v.ikm), v.label, &v.info);
            format!(
                "    {{\n      \"name\": \"{}\",\n      \"ikm_hex\": \"{}\",\n      \"label\": \"{}\",\n      \"info_hex\": \"{}\",\n      \"okm_hex\": \"{}\"\n    }}",
                v.name,
                hex(&v.ikm),
                v.label.purpose(),
                hex(&v.info),
                hex(okm.expose()),
            )
        })
        .collect();

    format!(
        "{{\n  \"description\": \"Known-answer vectors for kb_crypto::derive_key: HKDF-SHA256, salt = salt_hex, info = label_prefix || label || 0x00 || info, 32-byte output. Generated by crates/kb-crypto/examples/make_vectors.rs; never edit by hand.\",\n  \"suite\": 1,\n  \"salt_hex\": \"{}\",\n  \"label_prefix\": \"{}\",\n  \"vectors\": [\n{}\n  ]\n}}\n",
        hex(HKDF_SALT),
        LABEL_PREFIX,
        vectors.join(",\n"),
    )
}

// A minimal JSON writer with a fixed layout (two-space indentation, keys in the
// order given).

enum Json {
    Str(String),
    Num(u64),
    Bool(bool),
    Null,
    Arr(Vec<Json>),
    Obj(Vec<(&'static str, Json)>),
}

fn s(text: impl Into<String>) -> Json {
    Json::Str(text.into())
}

fn h(bytes: &[u8]) -> Json {
    Json::Str(hex(bytes))
}

fn n(value: impl Into<u64>) -> Json {
    Json::Num(value.into())
}

fn indent(out: &mut String, level: usize) {
    for _ in 0..level {
        out.push_str("  ");
    }
}

fn escape(text: &str, out: &mut String) {
    for c in text.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\t' => out.push_str("\\t"),
            c if u32::from(c) < 0x20 => out.push_str(&format!("\\u{:04x}", u32::from(c))),
            c => out.push(c),
        }
    }
}

impl Json {
    fn render(&self, level: usize, out: &mut String) {
        match self {
            Self::Str(text) => {
                out.push('"');
                escape(text, out);
                out.push('"');
            }
            Self::Num(value) => out.push_str(&value.to_string()),
            Self::Bool(value) => out.push_str(if *value { "true" } else { "false" }),
            Self::Null => out.push_str("null"),
            Self::Arr(items) if items.is_empty() => out.push_str("[]"),
            Self::Arr(items) => {
                out.push_str("[\n");
                for (i, item) in items.iter().enumerate() {
                    indent(out, level + 1);
                    item.render(level + 1, out);
                    out.push_str(if i + 1 < items.len() { ",\n" } else { "\n" });
                }
                indent(out, level);
                out.push(']');
            }
            Self::Obj(fields) => {
                out.push_str("{\n");
                for (i, (key, value)) in fields.iter().enumerate() {
                    indent(out, level + 1);
                    out.push('"');
                    escape(key, out);
                    out.push_str("\": ");
                    value.render(level + 1, out);
                    out.push_str(if i + 1 < fields.len() { ",\n" } else { "\n" });
                }
                indent(out, level);
                out.push('}');
            }
        }
    }
}

/// A golden file: description, suite, then the given fields.
fn golden(what: &str, fields: Vec<(&'static str, Json)>) -> String {
    let mut all = vec![
        (
            "description",
            s(format!(
                "Golden vectors for {what}. Generated by crates/kb-crypto/examples/make_vectors.rs from the fixed inputs below; random bytes come from kb_types::testing::SeededRng::new(rng_seed). Never edit by hand."
            )),
        ),
        ("suite", n(1u8)),
    ];
    all.extend(fields);
    let mut out = String::new();
    Json::Obj(all).render(0, &mut out);
    out.push('\n');
    out
}

fn wrap_file() -> String {
    let seed = 1;
    let kek = key_from(|i| 0x40 + i);
    let key = key_from(|i| 0x80 + i);
    let subject = b"space:0011223344556677/epoch:0";
    let wrapped = wrap_key(
        &Secret32::from_bytes(key),
        &Secret32::from_bytes(kek),
        subject,
        &SeededRng::new(seed),
    );
    golden(
        "kb_crypto::wrap_key (nonce || ciphertext || tag, AAD = atomik-kb/v1/wrap || subject)",
        vec![
            ("rng_seed", n(seed)),
            ("kek_hex", h(&kek)),
            ("key_hex", h(&key)),
            ("subject_hex", h(subject)),
            ("wrapped_hex", h(&wrapped.to_bytes())),
        ],
    )
}

fn passphrase_file() -> String {
    let key = key_from(|i| i);
    let passphrase = "correct horse battery staple";
    let subject = b"ark:install-0001";
    let cases = [
        (
            "small parameters (8 MiB, t = 1, p = 1)",
            2u64,
            Argon2Params {
                memory_kib: 8192,
                iterations: 1,
                parallelism: 1,
            },
        ),
        (
            "default parameters (64 MiB, t = 3, p = 4)",
            3u64,
            Argon2Params::DEFAULT,
        ),
    ];
    let blobs = cases
        .iter()
        .map(|(name, seed, params)| {
            let blob = wrap_with_passphrase(
                &Secret32::from_bytes(key),
                passphrase.as_bytes(),
                *params,
                subject,
                &SeededRng::new(*seed),
            )
            .unwrap();
            Json::Obj(vec![
                ("name", s(*name)),
                ("rng_seed", n(*seed)),
                ("memory_kib", n(params.memory_kib)),
                ("iterations", n(params.iterations)),
                ("parallelism", n(params.parallelism)),
                ("blob_hex", h(&blob.to_bytes())),
            ])
        })
        .collect();
    golden(
        "kb_crypto::wrap_with_passphrase (Argon2id, PassphraseWrapped::to_bytes layout v1)",
        vec![
            ("key_hex", h(&key)),
            ("passphrase_utf8", s(passphrase)),
            ("subject_hex", h(subject)),
            ("blobs", Json::Arr(blobs)),
        ],
    )
}

fn sign_file() -> String {
    let seed = key_from(|i| 0x10 + i);
    let signing = SigningKey::from_seed(&Secret32::from_bytes(seed));
    let cases = [
        ("device-log", b"genesis entry".as_slice()),
        ("envelope/head", b"".as_slice()),
    ];
    let signatures = cases
        .iter()
        .map(|(context, message)| {
            Json::Obj(vec![
                ("context", s(*context)),
                ("message_hex", h(message)),
                (
                    "signature_hex",
                    h(&sign(&signing, context, message).to_bytes()),
                ),
            ])
        })
        .collect();
    golden(
        "kb_crypto::sign (Ed25519 over atomik-kb/v1/ || context || 0x00 || message; deterministic, no rng)",
        vec![
            ("rng_seed", Json::Null),
            ("seed_hex", h(&seed)),
            ("public_hex", h(&signing.verifying_key().to_bytes())),
            ("signatures", Json::Arr(signatures)),
        ],
    )
}

fn sealed_box_file() -> String {
    let seed = 4;
    let recipient_seed = key_from(|i| 0x20 + i);
    let recipient = AgreementSecret::from_seed(&Secret32::from_bytes(recipient_seed));
    let context = "pairing/bundle";
    let plaintext = b"space key bundle";
    let sealed = seal_to(
        &recipient.public(),
        context,
        plaintext,
        &SeededRng::new(seed),
    );
    golden(
        "kb_crypto::seal_to (ephemeral public || nonce || ciphertext || tag)",
        vec![
            ("rng_seed", n(seed)),
            ("recipient_seed_hex", h(&recipient_seed)),
            ("recipient_public_hex", h(&recipient.public().to_bytes())),
            ("context", s(context)),
            ("plaintext_hex", h(plaintext)),
            ("sealed_hex", h(&sealed)),
        ],
    )
}

fn envelope_file() -> String {
    let key = key_from(|i| 0x30 + i);
    let signer_seed = key_from(|i| 0x50 + i);
    let signer = SigningKey::from_seed(&Secret32::from_bytes(signer_seed));
    let envelopes = EnvelopeKind::ALL
        .iter()
        .map(|&kind| {
            let seed = 10 + u64::from(kind.to_byte());
            // Kinds that travel between devices are signed by their author; the
            // local or self-authenticating ones (chunks are content-addressed,
            // backups and pairing messages are authenticated otherwise) are not.
            let signed = matches!(
                kind,
                EnvelopeKind::Entry
                    | EnvelopeKind::Snapshot
                    | EnvelopeKind::AccountDoc
                    | EnvelopeKind::Head
                    | EnvelopeKind::Membership
                    | EnvelopeKind::Presence
            );
            let header = format!("header of {}", kind.context());
            let plaintext = format!("plaintext of {}", kind.context());
            let bytes = seal_envelope(
                kind,
                header.as_bytes(),
                &Secret32::from_bytes(key),
                plaintext.as_bytes(),
                signed.then_some(&signer),
                &SeededRng::new(seed),
            );
            Json::Obj(vec![
                ("kind", s(kind.context().trim_start_matches("envelope/"))),
                ("kind_byte", n(kind.to_byte())),
                ("rng_seed", n(seed)),
                ("signed", Json::Bool(signed)),
                ("header_hex", h(header.as_bytes())),
                ("plaintext_hex", h(plaintext.as_bytes())),
                ("envelope_hex", h(&bytes)),
            ])
        })
        .collect();
    golden(
        "kb_crypto::seal_envelope (envelope v1, one per kind)",
        vec![
            ("key_hex", h(&key)),
            ("signer_seed_hex", h(&signer_seed)),
            ("signer_public_hex", h(&signer.verifying_key().to_bytes())),
            ("envelopes", Json::Arr(envelopes)),
        ],
    )
}

fn padding_file() -> String {
    let cases: [(u64, Vec<u8>); 2] = [
        (5, b"padded entry".to_vec()),
        (6, (0u16..300).map(|i| (i % 256) as u8).collect()),
    ];
    let padded = cases
        .iter()
        .map(|(seed, plaintext)| {
            Json::Obj(vec![
                ("rng_seed", n(*seed)),
                ("plaintext_hex", h(plaintext)),
                (
                    "padded_hex",
                    h(&pad_to_bucket(plaintext, &SeededRng::new(*seed))),
                ),
            ])
        })
        .collect();
    golden(
        "kb_crypto::pad_to_bucket (u32 LE length || plaintext || random padding to the bucket)",
        vec![("cases", Json::Arr(padded))],
    )
}

fn stream_file() -> String {
    let seed = 7;
    let key = key_from(|i| 0x60 + i);
    let aad_prefix = kb_crypto::hash(b"backup header");
    let chunks: [&[u8]; 3] = [b"chunk zero", b"chunk one", b"final chunk"];
    let rng = SeededRng::new(seed);
    let mut sealer = StreamSealer::new(Secret32::from_bytes(key), aad_prefix.to_vec());
    let sealed = chunks
        .iter()
        .enumerate()
        .map(|(i, chunk)| {
            let is_final = i + 1 == chunks.len();
            Json::Obj(vec![
                ("plaintext_hex", h(chunk)),
                ("is_final", Json::Bool(is_final)),
                (
                    "sealed_hex",
                    h(&sealer.seal_chunk(chunk, is_final, &rng).unwrap()),
                ),
            ])
        })
        .collect();
    golden(
        "kb_crypto::StreamSealer (three chunks, nonce || ciphertext || tag, AAD = prefix || index u64 LE || is_final u8)",
        vec![
            ("rng_seed", n(seed)),
            ("key_hex", h(&key)),
            ("aad_prefix_hex", h(&aad_prefix)),
            ("chunks", Json::Arr(sealed)),
        ],
    )
}

fn kit_file() -> String {
    let keys = [
        key_from(|i| i),
        key_from(|i| 0xff - i),
        [0u8; 32],
        [0xff; 32],
    ];
    let kits = keys
        .iter()
        .map(|key| {
            let rck = Secret32::from_bytes(*key);
            Json::Obj(vec![
                ("key_hex", h(key)),
                (
                    "words",
                    Json::Arr(kit::words(&rck).iter().map(|w| s(*w)).collect()),
                ),
                ("code", s(kit::code(&rck))),
            ])
        })
        .collect();
    golden(
        "the recovery kit encodings kb_crypto::kit::words and kb_crypto::kit::code (deterministic, no rng)",
        vec![("rng_seed", Json::Null), ("kits", Json::Arr(kits))],
    )
}

