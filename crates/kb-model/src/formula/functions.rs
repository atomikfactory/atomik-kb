//! The functions of the language (`formulas.md` section 3): names and arities. The typing rules are
//! the checker's, the semantics the evaluator's.

/// A built-in function.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(super) enum F {
    // Logic.
    If,
    Ifs,
    And,
    Or,
    Not,
    Empty,
    Equal,
    Unequal,
    // Numbers.
    Add,
    Subtract,
    Multiply,
    Divide,
    Mod,
    Pow,
    Abs,
    Ceil,
    Floor,
    Sqrt,
    Cbrt,
    Exp,
    Ln,
    Log10,
    Log2,
    Sign,
    Pi,
    E,
    Round,
    ToNumber,
    Min,
    Max,
    Sum,
    Mean,
    Median,
    // Text.
    Length,
    Substring,
    Contains,
    Test,
    Match,
    Replace,
    ReplaceAll,
    Split,
    Join,
    Lower,
    Upper,
    Trim,
    Repeat,
    PadStart,
    PadEnd,
    Format,
    // Dates.
    Now,
    Today,
    Minute,
    Hour,
    Day,
    Date,
    Week,
    Month,
    Year,
    DateAdd,
    DateSubtract,
    DateBetween,
    FormatDate,
    ParseDate,
    Timestamp,
    FromTimestamp,
    // Lists.
    At,
    First,
    Last,
    Slice,
    Concat,
    Sort,
    Reverse,
    Unique,
    Includes,
    Flat,
    Map,
    Filter,
    Find,
    FindIndex,
    Any,
    All,
    Count,
    // Pages, people and the rest.
    Prop,
    Id,
    Name,
    Email,
    Let,
    Lets,
}

/// A function's number of arguments (the receiver of a method call included).
#[derive(Debug, Clone, Copy)]
pub(super) struct Info {
    pub f: F,
    pub min: usize,
    /// `None` for no limit.
    pub max: Option<usize>,
}

const fn fixed(f: F, count: usize) -> Option<Info> {
    Some(Info {
        f,
        min: count,
        max: Some(count),
    })
}

const fn range(f: F, min: usize, max: usize) -> Option<Info> {
    Some(Info {
        f,
        min,
        max: Some(max),
    })
}

const fn at_least(f: F, min: usize) -> Option<Info> {
    Some(Info { f, min, max: None })
}

/// The function with this name (exact, case sensitive).
pub(super) fn lookup(name: &str) -> Option<Info> {
    match name {
        "if" => fixed(F::If, 3),
        "ifs" => at_least(F::Ifs, 3),
        "and" => at_least(F::And, 2),
        "or" => at_least(F::Or, 2),
        "not" => fixed(F::Not, 1),
        "empty" => fixed(F::Empty, 1),
        "equal" => fixed(F::Equal, 2),
        "unequal" => fixed(F::Unequal, 2),
        "add" => fixed(F::Add, 2),
        "subtract" => fixed(F::Subtract, 2),
        "multiply" => fixed(F::Multiply, 2),
        "divide" => fixed(F::Divide, 2),
        "mod" => fixed(F::Mod, 2),
        "pow" => fixed(F::Pow, 2),
        "abs" => fixed(F::Abs, 1),
        "ceil" => fixed(F::Ceil, 1),
        "floor" => fixed(F::Floor, 1),
        "sqrt" => fixed(F::Sqrt, 1),
        "cbrt" => fixed(F::Cbrt, 1),
        "exp" => fixed(F::Exp, 1),
        "ln" => fixed(F::Ln, 1),
        "log10" => fixed(F::Log10, 1),
        "log2" => fixed(F::Log2, 1),
        "sign" => fixed(F::Sign, 1),
        "pi" => fixed(F::Pi, 0),
        "e" => fixed(F::E, 0),
        "round" => range(F::Round, 1, 2),
        "toNumber" => fixed(F::ToNumber, 1),
        "min" => at_least(F::Min, 1),
        "max" => at_least(F::Max, 1),
        "sum" => at_least(F::Sum, 1),
        "mean" => at_least(F::Mean, 1),
        "median" => at_least(F::Median, 1),
        "length" => fixed(F::Length, 1),
        "substring" => range(F::Substring, 2, 3),
        "contains" => fixed(F::Contains, 2),
        "test" => fixed(F::Test, 2),
        "match" => fixed(F::Match, 2),
        "replace" => fixed(F::Replace, 3),
        "replaceAll" => fixed(F::ReplaceAll, 3),
        "split" => fixed(F::Split, 2),
        "join" => fixed(F::Join, 2),
        "lower" => fixed(F::Lower, 1),
        "upper" => fixed(F::Upper, 1),
        "trim" => fixed(F::Trim, 1),
        "repeat" => fixed(F::Repeat, 2),
        "padStart" => fixed(F::PadStart, 3),
        "padEnd" => fixed(F::PadEnd, 3),
        "format" => fixed(F::Format, 1),
        "now" => fixed(F::Now, 0),
        "today" => fixed(F::Today, 0),
        "minute" => fixed(F::Minute, 1),
        "hour" => fixed(F::Hour, 1),
        "day" => fixed(F::Day, 1),
        "date" => fixed(F::Date, 1),
        "week" => fixed(F::Week, 1),
        "month" => fixed(F::Month, 1),
        "year" => fixed(F::Year, 1),
        "dateAdd" => fixed(F::DateAdd, 3),
        "dateSubtract" => fixed(F::DateSubtract, 3),
        "dateBetween" => fixed(F::DateBetween, 3),
        "formatDate" => fixed(F::FormatDate, 2),
        "parseDate" => fixed(F::ParseDate, 1),
        "timestamp" => fixed(F::Timestamp, 1),
        "fromTimestamp" => fixed(F::FromTimestamp, 1),
        "at" => fixed(F::At, 2),
        "first" => fixed(F::First, 1),
        "last" => fixed(F::Last, 1),
        "slice" => range(F::Slice, 2, 3),
        "concat" => at_least(F::Concat, 1),
        "sort" => fixed(F::Sort, 1),
        "reverse" => fixed(F::Reverse, 1),
        "unique" => fixed(F::Unique, 1),
        "includes" => fixed(F::Includes, 2),
        "flat" => fixed(F::Flat, 1),
        "map" => fixed(F::Map, 2),
        "filter" => fixed(F::Filter, 2),
        "find" => fixed(F::Find, 2),
        "findIndex" => fixed(F::FindIndex, 2),
        "some" => fixed(F::Any, 2),
        "every" => fixed(F::All, 2),
        "count" => range(F::Count, 1, 2),
        "prop" => range(F::Prop, 1, 2),
        "id" => range(F::Id, 0, 1),
        "name" => fixed(F::Name, 1),
        "email" => fixed(F::Email, 1),
        "let" => fixed(F::Let, 3),
        "lets" => at_least(F::Lets, 3),
        _ => None,
    }
}

/// Whether a let-bound name would shadow a function or one of the names the language binds itself.
pub(super) fn is_reserved_name(name: &str) -> bool {
    name == "current" || name == "index" || lookup(name).is_some()
}
